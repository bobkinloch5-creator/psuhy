import { createClient } from "@/lib/supabase/server"
import { NextResponse } from "next/server"

export async function POST(request: Request) {
    try {
        const supabase = await createClient()
        const {
            data: { user },
        } = await supabase.auth.getUser()

        if (!user) {
            return NextResponse.json({ error: "Unauthorized" }, { status: 401 })
        }

        const { creationId, assetName, description } = await request.json()

        if (!creationId || !assetName) {
            return NextResponse.json(
                { error: "Creation ID and asset name required" },
                { status: 400 }
            )
        }

        const { data: userData } = await supabase
            .from("users")
            .select("id")
            .eq("discord_id", user.id)
            .single()

        if (!userData) {
            return NextResponse.json({ error: "User not found" }, { status: 404 })
        }

        // Get creation
        const { data: creation } = await supabase
            .from("creations")
            .select("*")
            .eq("id", creationId)
            .eq("user_id", userData.id)
            .single()

        if (!creation) {
            return NextResponse.json({ error: "Creation not found" }, { status: 404 })
        }

        // Get model file URL (FBX preferred for Roblox)
        const modelData = creation.asset_data
        const modelUrl = modelData?.download_url || modelData?.model_url

        if (!modelUrl) {
            return NextResponse.json(
                { error: "Model file not available" },
                { status: 404 }
            )
        }

        // Fetch model file
        const fileResponse = await fetch(modelUrl)
        if (!fileResponse.ok) {
            throw new Error("Failed to fetch model file")
        }

        const fileBuffer = await fileResponse.arrayBuffer()
        const fileBlob = new Blob([fileBuffer])

        // Prepare form data for Roblox Open Cloud API
        const formData = new FormData()

        // Request metadata
        formData.append(
            "request",
            JSON.stringify({
                assetType: "Model",
                displayName: assetName,
                description: description || `Generated by BlaxSmith AI: ${creation.prompt}`,
                creationContext: {
                    creator: {
                        userId: process.env.ROBLOX_USER_ID || "", // Set in env
                    },
                },
            })
        )

        // File content
        formData.append("fileContent", fileBlob, `${assetName}.fbx`)

        // Upload to Roblox Open Cloud
        const uploadResponse = await fetch(
            "https://apis.roblox.com/assets/v1/assets",
            {
                method: "POST",
                headers: {
                    "x-api-key": process.env.ROBLOX_OPEN_CLOUD_KEY || "",
                },
                body: formData,
            }
        )

        if (!uploadResponse.ok) {
            const errorText = await uploadResponse.text()
            console.error("[Roblox Upload] Error:", errorText)
            throw new Error(`Roblox upload failed: ${uploadResponse.status}`)
        }

        const uploadResult = await uploadResponse.json()

        // Track upload in database
        const { data: robloxAsset } = await supabase
            .from("roblox_assets")
            .insert({
                creation_id: creationId,
                user_id: userData.id,
                roblox_asset_id: uploadResult.assetId || uploadResult.path?.split("/").pop(),
                asset_name: assetName,
                asset_type: "Model",
                upload_status: uploadResult.assetId ? "completed" : "processing",
                asset_url: uploadResult.assetId
                    ? `https://www.roblox.com/library/${uploadResult.assetId}`
                    : null,
            })
            .select()
            .single()

        return NextResponse.json({
            success: true,
            assetId: uploadResult.assetId || uploadResult.path?.split("/").pop(),
            assetUrl: robloxAsset?.asset_url,
            operationId: uploadResult.path, // For checking upload status
        })
    } catch (error) {
        console.error("[Roblox Upload] Error:", error)
        return NextResponse.json(
            { error: "Failed to upload to Roblox" },
            { status: 500 }
        )
    }
}
