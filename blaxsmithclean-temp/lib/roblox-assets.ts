// Get all assets for a theme
export function getAssetsForTheme(theme: string): Array<{ id: number; name: string; category: string }> {
    const lowerTheme = theme.toLowerCase()
    const categories = THEME_ASSETS[lowerTheme] || ["trees", "rocks", "buildings", "props"]
    const assets: Array<{ id: number; name: string; category: string }> = []

    for (const cat of categories) {
        const catAssets = VERIFIED_ASSETS[cat as keyof typeof VERIFIED_ASSETS]
        if (catAssets) {
            assets.push(...catAssets.map(a => ({ id: a.id, name: a.name, category: a.category })))
        }
    }

    return assets
}

// Get random assets with positions for world generation
export function getRandomAssets(
    count: number,
    theme?: string
): Array<{ id: number; name: string; category: string; position: { x: number; y: number; z: number } }> {
    // Get assets for theme or use default mix
    const allAssets = theme
        ? getAssetsForTheme(theme)
        : Object.values(VERIFIED_ASSETS).flat().map(a => ({ id: a.id, name: a.name, category: a.category }))

    // Shuffle
    const shuffled = [...allAssets].sort(() => Math.random() - 0.5)
    const selected = shuffled.slice(0, Math.min(count, shuffled.length))

    // Add positions in a grid/circular pattern
    return selected.map((asset, index) => {
        const gridSize = Math.ceil(Math.sqrt(count))
        const row = Math.floor(index / gridSize)
        const col = index % gridSize
        const spacing = 25 // studs between assets

        // Circular pattern with some randomness
        const angle = (index / count) * Math.PI * 2
        const radius = 30 + Math.random() * 50
        const useGrid = count > 10

        return {
            ...asset,
            position: useGrid
                ? {
                    x: (col - gridSize / 2) * spacing + (Math.random() - 0.5) * 10,
                    y: 0,
                    z: (row - gridSize / 2) * spacing + (Math.random() - 0.5) * 10,
                }
                : {
                    x: Math.cos(angle) * radius + (Math.random() - 0.5) * 15,
                    y: 0,
                    z: Math.sin(angle) * radius + (Math.random() - 0.5) * 15,
                },
        }
    })
}

// Search assets by keyword
export function searchAssets(query: string): Array<{ id: number; name: string; category: string }> {
    const lowerQuery = query.toLowerCase()
    const allAssets = Object.values(VERIFIED_ASSETS).flat()

    // Search by name, category, or theme
    const matches = allAssets.filter(asset =>
        asset.name.toLowerCase().includes(lowerQuery) ||
        asset.category.toLowerCase().includes(lowerQuery) ||
        asset.theme?.some(t => t.toLowerCase().includes(lowerQuery))
    )

    return matches.slice(0, 20).map(a => ({ id: a.id, name: a.name, category: a.category }))
}

// Get assets by category
export function getAssetsByCategory(categoryName: string): Array<{ id: number; name: string; category: string }> {
    const key = categoryName.toLowerCase()
    const assets = VERIFIED_ASSETS[key as keyof typeof VERIFIED_ASSETS]
    return assets ? assets.map(a => ({ id: a.id, name: a.name, category: a.category })) : []
}

// Find best matching asset
export function findBestAsset(request: string): { id: number; name: string; category: string } | null {
    const results = searchAssets(request)
    return results.length > 0 ? results[0] : null
}

// Get asset for a specific category and theme
export function getAssetForCategoryAndTheme(category: string, theme: string): { id: number; name: string; category: string } | null {
    const allAssets = Object.values(VERIFIED_ASSETS).flat()

    // Find asset matching both category and theme
    const matches = allAssets.filter(asset =>
        asset.category.toLowerCase() === category.toLowerCase() &&
        asset.theme?.some(t => t.toLowerCase() === theme.toLowerCase())
    )

    if (matches.length > 0) {
        const random = matches[Math.floor(Math.random() * matches.length)]
        return { id: random.id, name: random.name, category: random.category }
    }

    // Fallback to just category
    const categoryMatches = allAssets.filter(asset =>
        asset.category.toLowerCase() === category.toLowerCase()
    )

    if (categoryMatches.length > 0) {
        const random = categoryMatches[Math.floor(Math.random() * categoryMatches.length)]
        return { id: random.id, name: random.name, category: random.category }
    }

    return null
}

